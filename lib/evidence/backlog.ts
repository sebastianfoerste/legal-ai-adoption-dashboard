import { formatDate } from "../engagement/as-of";
import { EVIDENCE_SOURCE_FILE } from "./data";
import {
  decisionLabel,
  deliveryStatusLabel,
  evidenceTypeLabel,
  outcomeStatusLabel,
  problemClassLabel,
  type ChangeView,
  type TaskSetSummary,
} from "./loop";
import type { EvidenceStore, EvidenceType } from "./schema";

const row = (cells: (string | number)[]) => `| ${cells.join(" | ")} |`;

export function evidenceSummary(view: ChangeView): string {
  const parts = (Object.keys(view.evidenceByType) as EvidenceType[])
    .filter((type) => view.evidenceByType[type] > 0)
    .map((type) => `${view.evidenceByType[type]} ${evidenceTypeLabel[type].toLowerCase()}`);
  const support = parts.length > 0 ? parts.join(", ") : "no study observation";
  return view.contradicting.length > 0
    ? `${support}; ${view.contradicting.length} contradicting`
    : support;
}

const minutes = (value: number | null) => (value === null ? "none reached" : `${value} min`);

const comparisonRow = (label: string, pick: (set: TaskSetSummary) => string | number, view: ChangeView) =>
  view.comparison ? row([label, pick(view.comparison.baseline), pick(view.comparison.followUp)]) : "";

/** The evidence-linked backlog: one entry per change, from research question to outcome. */
export function renderEvidenceBacklogMarkdown(
  store: EvidenceStore,
  views: ChangeView[],
  asOf: string,
): string {
  const lines: string[] = [
    "# Evidence-linked backlog",
    "",
    `> ${store.notice}`,
    "",
    `As of ${formatDate(asOf)}. Source: \`${EVIDENCE_SOURCE_FILE}\` (\`${store.schema}\`). Generated by \`lib/evidence/backlog.ts\`; do not edit by hand.`,
    "",
    `Practitioner study "${store.study.workflow}": ${store.study.sessionsCompleted} sessions completed, ${store.study.invitationsSent} invitations sent, recruitment ${store.study.recruitmentAuthorised ? "authorised" : "not authorised"}. ${store.study.note}`,
    "",
    row(["Change", "Problem class", "Evidence", "Decision", "Confidence", "Delivery", "Outcome", "Next decision", "Owner"]),
    row(Array(9).fill("---")),
    ...views.map((view) =>
      row([
        `${view.change.id} ${view.change.title}`,
        problemClassLabel[view.problem.class],
        evidenceSummary(view),
        decisionLabel[view.change.decision.status],
        view.change.decision.confidence,
        deliveryStatusLabel[view.deliveryStatus],
        outcomeStatusLabel[view.outcomeStatus],
        view.change.nextDecision.question,
        view.change.nextDecision.ownerRole,
      ]),
    ),
    "",
  ];

  for (const view of views) {
    const { change, problem } = view;
    const release = change.delivery.release;
    lines.push(
      `## ${change.id}: ${change.title}`,
      "",
      `- Research questions: ${view.questions.map((q) => q.id).join(", ") || "none"}`,
      `- Sessions: ${view.sessions.map((s) => `${s.id} (${s.roleLabel}, ${s.kind.replaceAll("_", " ")})`).join("; ") || "none"}`,
      `- Problem (${problem.id}, ${problemClassLabel[problem.class].toLowerCase()}): ${problem.statement}`,
      "",
      "**Observed**",
      "",
      ...(view.supporting.length > 0
        ? view.supporting.map((o) => `- ${o.id}, ${evidenceTypeLabel[o.evidenceType].toLowerCase()}: ${o.observed}`)
        : ["- No study observation."]),
      ...view.contradicting.map(
        (o) => `- Contradicting, ${o.id}, ${evidenceTypeLabel[o.evidenceType].toLowerCase()}: ${o.observed}`,
      ),
      "",
      `**Interpretation** (${problem.interpretedByRole}): ${problem.interpretation}`,
      "",
      `- Hypothesis: ${change.hypothesis}`,
      `- Proposed change: ${change.proposedChange}`,
      `- Decision: ${decisionLabel[change.decision.status].toLowerCase()} on ${formatDate(change.decision.decidedOn)}, confidence ${change.decision.confidence} (${change.decision.decidedByRole}). ${change.decision.rationale}`,
      ...(change.decision.revisitOn ? [`- Revisit on: ${formatDate(change.decision.revisitOn)}`] : []),
      `- Acceptance criteria${change.criteriaRecordedOn ? ` (recorded ${formatDate(change.criteriaRecordedOn)})` : ""}: ${change.acceptanceCriteria.map((c) => `${c.id} ${c.text}`).join(" ") || "none recorded"}`,
      `- Implementation reference: ${change.delivery.implementationRef ?? "none"}`,
      `- Delivery: ${deliveryStatusLabel[view.deliveryStatus].toLowerCase()}${release ? ` on ${formatDate(release.releasedOn)}, evidence: ${release.evidenceRef}` : ""}`,
      `- Outcome: ${outcomeStatusLabel[view.outcomeStatus]}${change.outcome ? `. ${change.outcome.rationale}` : ""}`,
      "",
    );
    if (view.comparison) {
      lines.push(
        `**Follow-up comparison.** ${view.comparison.comparability}`,
        "",
        row(["Measure", "Baseline", "Follow-up"]),
        row(["---", "---", "---"]),
        comparisonRow("Sessions", (s) => s.sessions, view),
        comparisonRow("Acceptable result reached", (s) => `${s.acceptable} of ${s.sessions}`, view),
        comparisonRow("Completed unaided", (s) => s.completedUnaided, view),
        comparisonRow("Moderator prompts", (s) => s.assistance, view),
        comparisonRow("Interpretation errors", (s) => s.interpretationErrors, view),
        comparisonRow("Trust concerns", (s) => s.trustConcerns, view),
        comparisonRow("Median minutes to an acceptable result", (s) => minutes(s.medianMinutesToAcceptable), view),
        "",
        "Other plausible causes:",
        "",
        ...view.comparison.caveats.map((caveat) => `- ${caveat}`),
        "",
      );
    }
    lines.push(
      "**Missing observations**",
      "",
      ...(view.missingObservations.length > 0
        ? view.missingObservations.map((item) => `- ${item}`)
        : ["- None recorded."]),
      "",
      `**Next decision:** ${change.nextDecision.question} Owner: ${change.nextDecision.ownerRole}${change.nextDecision.dueOn ? `, by ${formatDate(change.nextDecision.dueOn)}` : ""}.`,
      "",
    );
  }
  lines.push(store.notice, "");
  return lines.join("\n");
}
